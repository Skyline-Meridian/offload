// Lists which models have createdById / updatedById columns, so the Prisma client extension
// in src/server/db.ts knows where to fill them. Run after changing prisma/schema.prisma.
import { readFileSync, writeFileSync } from 'node:fs'

const schema = readFileSync('prisma/schema.prisma', 'utf8')
const created = []
const updated = []

for (const match of schema.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)) {
  const [, name, body] = match
  if (/^\s*createdById\s/m.test(body)) created.push(name)
  if (/^\s*updatedById\s/m.test(body)) updated.push(name)
}

const list = (items) => items.map((n) => `  '${n}',`).join('\n')
const out = `// Generated by scripts/gen-actor-models.mjs. Do not edit by hand.
export const modelsWithCreatedBy: ReadonlySet<string> = new Set([
${list(created)}
])

export const modelsWithUpdatedBy: ReadonlySet<string> = new Set([
${list(updated)}
])
`
writeFileSync('src/server/actor-models.ts', out)
process.stdout.write(`created: ${created.length}, updated: ${updated.length}\n`)
